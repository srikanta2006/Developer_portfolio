"use client";

import { useState } from "react";
import { Play, RotateCcw, Scale, Shield, Landmark } from "lucide-react";

interface Scenario {
  id: string;
  title: string;
  description: string;
  prosecutionArg: string;
  defenceArg: string;
  judgeVerdict: string;
  statute: string;
}

const SCENARIOS: Scenario[] = [
  {
    id: "ip-copyright",
    title: "AI Training & Copyright Infringement",
    description: "Whether ingesting copyrighted codebases without express commercial consent violates Fair Dealing doctrine.",
    prosecutionArg:
      "The defendant foundation model reproduced proprietary algorithmic structures verbatim without licensing, bypassing fair-use boundaries and causing measurable market dilution to original repository authors under Section 52(1)(a) of the Copyright Act.",
    defenceArg:
      "The ingestion was exclusively transformative. Intermediate model representations generate synthetic outputs with demonstrable orthogonal utility, satisfying transformative non-infringing innovation standards established in statutory safe harbors.",
    judgeVerdict:
      "Verdict: Partial Violation with Restitution. Ingestion for statistical pattern extraction is permissible; however, unconstrained verbatim token generation lacks sufficient transformative divergence. Compulsory royalty escrow mandated.",
    statute: "Indian Copyright Act §52(1) / Berne Convention Art. 9(2)",
  },
  {
    id: "defi-liability",
    title: "DeFi Autonomous Execution Liability",
    description: "Assigning liability when an autonomous multi-agent flash-loan execution triggers cascading algorithmic insolvency.",
    prosecutionArg:
      "The deployment agent possessed predictable telemetry regarding slippage vulnerability. Releasing an unsupervised agentic arbitrage loop without emergency halt-guards constitutes actionable algorithmic gross negligence.",
    defenceArg:
      "Smart contracts execute immutable bytecode strictly according to decentralized consensus rules. The opposing liquidity pool was exposed to transparent market dynamics; no malicious exploit payload was introduced.",
    judgeVerdict:
      "Verdict: Operator Negligence Established. While protocol execution is decentralized, the deployer holds a fiduciary duty of care when configuring autonomous agent execution parameters exceeding 100x leverage ratios.",
    statute: "Law of Torts (Negligent Design) / IT Act §43A & §79",
  },
  {
    id: "synthetic-slander",
    title: "Synthetic Media Defamation",
    description: "Determining whether an enterprise is liable for hallucinatory defamatory claims generated by its customer-facing LLM.",
    prosecutionArg:
      "The business deployed a live customer support agent without hallucination circuit-breakers, publishing fabricated criminal accusations against the plaintiff in a public chat session with irreversible reputational harm.",
    defenceArg:
      "The enterprise provided conspicuous disclaimers that AI responses may contain inaccuracies. Under intermediary safe harbor provisions, the provider is shielded as a neutral technology transmitter.",
    judgeVerdict:
      "Verdict: Intermediary Immunity Denied. Disclaimers cannot exonerate a party that directly synthesizes and broadcasts demonstrably false allegations without baseline verification guardrails.",
    statute: "Defamation §499 IPC / Intermediary Guidelines Rule 3(1)(b)",
  },
];

export function LegalArenaSimulator() {
  const [selectedScenario, setSelectedScenario] = useState<Scenario>(SCENARIOS[0]);
  const [activeStep, setActiveStep] = useState<number>(0);
  const [isRunning, setIsRunning] = useState<boolean>(false);
  const [activeTab, setActiveTab] = useState<"debate" | "architecture">("debate");

  const startSimulation = () => {
    setIsRunning(true);
    setActiveStep(1);

    setTimeout(() => {
      setActiveStep(2);
    }, 1200);

    setTimeout(() => {
      setActiveStep(3);
      setIsRunning(false);
    }, 2400);
  };

  const resetSimulation = () => {
    setActiveStep(0);
    setIsRunning(false);
  };

  return (
    <div className="rounded-2xl border border-white/10 bg-[#0B0F19] p-4 sm:p-6 space-y-5 text-slate-200 shadow-xl">
      {/* Simulator Header */}
      <div className="flex flex-wrap items-center justify-between gap-3 border-b border-white/[0.08] pb-4">
        <div className="flex items-center gap-2.5">
          <div className="p-2 rounded-xl bg-indigo-500/20 text-[#A5B4FC]">
            <Scale className="h-4 w-4" />
          </div>
          <div>
            <h4 className="font-heading text-sm sm:text-base font-bold text-white flex items-center gap-2">
              LegalArena Multi-Agent Courtroom
              <span className="inline-flex items-center gap-1 font-mono text-[10px] bg-emerald-500/15 text-emerald-300 px-2 py-0.5 rounded-full border border-emerald-500/30">
                <span className="h-1.5 w-1.5 rounded-full bg-emerald-400 animate-pulse" />
                LangGraph State Machine
              </span>
            </h4>
            <p className="text-xs text-[#94A3B8]">
              Simulate adversarial reasoning between specialized Prosecution, Defence &amp; Judge agents
            </p>
          </div>
        </div>

        {/* Tab Toggle */}
        <div className="flex items-center gap-1 p-1 rounded-xl bg-white/[0.04] border border-white/10 text-xs font-mono">
          <button
            type="button"
            onClick={() => setActiveTab("debate")}
            className={`px-3 py-1 rounded-lg transition-all ${
              activeTab === "debate"
                ? "bg-[#6366F1] text-white font-semibold shadow-xs"
                : "text-slate-400 hover:text-white"
            }`}
          >
            Live Debate
          </button>
          <button
            type="button"
            onClick={() => setActiveTab("architecture")}
            className={`px-3 py-1 rounded-lg transition-all ${
              activeTab === "architecture"
                ? "bg-[#6366F1] text-white font-semibold shadow-xs"
                : "text-slate-400 hover:text-white"
            }`}
          >
            Agent Roles &amp; Tools
          </button>
        </div>
      </div>

      {/* Scenario Selector Pills */}
      <div className="space-y-2">
        <span className="font-mono text-[11px] uppercase tracking-wider text-[#94A3B8]">
          Choose Dispute Scenario:
        </span>
        <div className="flex flex-wrap gap-2">
          {SCENARIOS.map((scenario) => (
            <button
              key={scenario.id}
              type="button"
              onClick={() => {
                setSelectedScenario(scenario);
                resetSimulation();
              }}
              className={`px-3 py-1.5 rounded-xl text-xs font-medium text-left border transition-all cursor-pointer ${
                selectedScenario.id === scenario.id
                  ? "bg-[#6366F1]/20 border-[#6366F1] text-white shadow-xs font-semibold"
                  : "bg-white/[0.04] border-white/10 text-slate-300 hover:border-white/20 hover:text-white"
              }`}
            >
              {scenario.title}
            </button>
          ))}
        </div>
      </div>

      {activeTab === "debate" ? (
        <div className="space-y-4">
          {/* Action trigger: Run Simulation */}
          <div className="flex flex-wrap items-center justify-between gap-3 p-3.5 rounded-xl bg-white/[0.03] border border-white/10">
            <p className="text-xs text-slate-300 line-clamp-1 flex-1">
              <strong className="text-white">Context:</strong> {selectedScenario.description}
            </p>
            <div className="flex items-center gap-2">
              {activeStep === 0 ? (
                <button
                  type="button"
                  onClick={startSimulation}
                  disabled={isRunning}
                  className="inline-flex items-center gap-1.5 px-3.5 py-1.5 rounded-xl bg-[#6366F1] hover:bg-[#4F46E5] text-white text-xs font-semibold shadow-md shadow-indigo-500/25 transition-all cursor-pointer active:scale-95"
                >
                  <Play className="h-3.5 w-3.5 fill-current" />
                  <span>Run Agent Debate</span>
                </button>
              ) : (
                <button
                  type="button"
                  onClick={resetSimulation}
                  className="inline-flex items-center gap-1.5 px-3.5 py-1.5 rounded-xl bg-white/[0.06] border border-white/10 hover:bg-white/[0.1] text-white text-xs font-medium transition-colors cursor-pointer"
                >
                  <RotateCcw className="h-3 w-3" />
                  <span>Reset Debate</span>
                </button>
              )}
            </div>
          </div>

          {/* Stepper Status Indicators */}
          <div className="grid grid-cols-3 gap-2 text-center text-xs font-mono">
            <div
              className={`p-2 rounded-xl border transition-all ${
                activeStep >= 1
                  ? "bg-red-500/15 border-red-500/30 text-red-300 font-semibold"
                  : "bg-white/[0.02] border-white/10 text-slate-500"
              }`}
            >
              1. Prosecution Agent
            </div>
            <div
              className={`p-2 rounded-xl border transition-all ${
                activeStep >= 2
                  ? "bg-blue-500/15 border-blue-500/30 text-blue-300 font-semibold"
                  : "bg-white/[0.02] border-white/10 text-slate-500"
              }`}
            >
              2. Defence Agent
            </div>
            <div
              className={`p-2 rounded-xl border transition-all ${
                activeStep >= 3
                  ? "bg-purple-500/20 border-purple-500/40 text-purple-300 font-semibold"
                  : "bg-white/[0.02] border-white/10 text-slate-500"
              }`}
            >
              3. Judge Verdict
            </div>
          </div>

          {/* Streamed Dialogue Box */}
          <div className="space-y-3 pt-1">
            {activeStep === 0 && (
              <div className="p-8 rounded-2xl border border-dashed border-white/15 bg-white/[0.02] text-center space-y-2">
                <Scale className="h-6 w-6 text-[#818CF8] mx-auto opacity-70" />
                <p className="text-xs text-[#94A3B8]">
                  Click <strong className="text-white">&quot;Run Agent Debate&quot;</strong> to watch LangChain agents formulate arguments and stream a reasoned judicial verdict in real-time.
                </p>
              </div>
            )}

            {/* Step 1: Prosecution */}
            {activeStep >= 1 && (
              <div className="p-4 sm:p-5 rounded-2xl border border-red-500/30 bg-red-950/20 shadow-lg space-y-2 animate-in fade-in slide-in-from-top-1 duration-300">
                <div className="flex items-center justify-between text-xs font-semibold text-red-300">
                  <span className="flex items-center gap-1.5">
                    <Scale className="h-4 w-4" />
                    Prosecution Agent (LangChain + ChromaDB Retrieval)
                  </span>
                  <span className="font-mono text-[10px] text-red-400/80">Round 1</span>
                </div>
                <p className="text-xs text-red-100/90 leading-relaxed font-sans">
                  {selectedScenario.prosecutionArg}
                </p>
              </div>
            )}

            {/* Step 2: Defence */}
            {activeStep >= 2 && (
              <div className="p-4 sm:p-5 rounded-2xl border border-blue-500/30 bg-blue-950/20 shadow-lg space-y-2 animate-in fade-in slide-in-from-top-1 duration-300">
                <div className="flex items-center justify-between text-xs font-semibold text-blue-300">
                  <span className="flex items-center gap-1.5">
                    <Shield className="h-4 w-4" />
                    Defence Agent (Rebuttal State)
                  </span>
                  <span className="font-mono text-[10px] text-blue-400/80">Round 2</span>
                </div>
                <p className="text-xs text-blue-100/90 leading-relaxed font-sans">
                  {selectedScenario.defenceArg}
                </p>
              </div>
            )}

            {/* Step 3: Judge Verdict */}
            {activeStep >= 3 && (
              <div className="p-5 sm:p-6 rounded-2xl border border-purple-500/40 bg-purple-950/30 shadow-xl space-y-2 animate-in fade-in slide-in-from-top-2 duration-300">
                <div className="flex items-center justify-between text-xs font-bold text-purple-300">
                  <span className="flex items-center gap-1.5">
                    <Landmark className="h-4 w-4" />
                    Judge Agent (LangGraph State Synthesis)
                  </span>
                  <span className="font-mono text-[10px] px-2 py-0.5 rounded-full bg-purple-500/20 text-purple-200 border border-purple-500/30">
                    Reasoned Verdict
                  </span>
                </div>
                <p className="text-xs text-purple-100 leading-relaxed font-sans font-medium">
                  {selectedScenario.judgeVerdict}
                </p>
                <div className="pt-2 border-t border-purple-500/20 text-[11px] font-mono text-purple-300/80">
                  Statutory Basis: {selectedScenario.statute}
                </div>
              </div>
            )}
          </div>
        </div>
      ) : (
        /* Architecture Roles Tab */
        <div className="grid grid-cols-1 md:grid-cols-3 gap-3">
          <div className="p-4 rounded-xl border border-white/10 bg-white/[0.03] space-y-2 text-xs">
            <div className="flex items-center gap-1.5 font-bold text-red-300">
              <Scale className="h-4 w-4" />
              <span>Prosecution Agent</span>
            </div>
            <p className="text-slate-300">
              <strong className="text-white">Role:</strong> Identifies violations, extracts statutory clauses, and builds initial adversarial claim.
            </p>
            <div className="font-mono text-[10px] text-slate-200 bg-[#0B0F19] p-2.5 rounded-lg border border-white/10">
              Tools: ChromaDB Vector Query, LangChain Document Retriever
            </div>
          </div>

          <div className="p-4 rounded-xl border border-white/10 bg-white/[0.03] space-y-2 text-xs">
            <div className="flex items-center gap-1.5 font-bold text-blue-300">
              <Shield className="h-4 w-4" />
              <span>Defence Agent</span>
            </div>
            <p className="text-slate-300">
              <strong className="text-white">Role:</strong> Formulates counterarguments, challenges evidence validity, and asserts affirmative defenses.
            </p>
            <div className="font-mono text-[10px] text-slate-200 bg-[#0B0F19] p-2.5 rounded-lg border border-white/10">
              Tools: Precedent Cross-Checker, Fair-Use Evaluator
            </div>
          </div>

          <div className="p-4 rounded-xl border border-white/10 bg-white/[0.03] space-y-2 text-xs">
            <div className="flex items-center gap-1.5 font-bold text-purple-300">
              <Landmark className="h-4 w-4" />
              <span>Judge Agent</span>
            </div>
            <p className="text-slate-300">
              <strong className="text-white">Role:</strong> Orchestrated via LangGraph. Evaluates debate completeness, scores arguments, and outputs verdict.
            </p>
            <div className="font-mono text-[10px] text-slate-200 bg-[#0B0F19] p-2.5 rounded-lg border border-white/10">
              Tools: Structured Output Parser, Multi-Turn State Machine
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
